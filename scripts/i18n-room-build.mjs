#!/usr/bin/env node
// Embeds the English room dictionary + a per-player bootstrap into
// public/game.html (the shared /play room — no locale in URL), and writes the
// other locales out as small standalone JSON files under public/i18n/ that the
// bootstrap fetches on demand. Each player sees their own language, read from
// localStorage 'hk_lang' (set by the localized landing/macos pages) with a
// navigator.language fallback. Only English ships inline so every /play load
// doesn't pay for all N locales — non-English players fetch one ~5KB file
// instead. The bootstrap defines window.t (used by public/game.js) and fills
// [data-i18n]/[data-i18n-ph]/[data-i18n-html] elements on load, then re-fills
// once a fetched locale lands. Idempotent: rewrites between markers.
//   Usage: node scripts/i18n-room-build.mjs   (run after i18n-room-translate.mjs)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const LOCALES = ['en', 'es', 'pt-br', 'fr', 'de', 'vi', 'th'];
const flat = (o) => ({ ...o.static, ...o.runtime });

const dict = {};
for (const loc of LOCALES) {
  const file = loc === 'en' ? 'i18n/room.en.json' : `i18n/room.${loc}.json`;
  const p = join(ROOT, file);
  if (!existsSync(p)) { console.warn(`  ⚠ missing ${file} — falling back to en for ${loc}`); dict[loc] = null; continue; }
  dict[loc] = flat(JSON.parse(readFileSync(p, 'utf8')));
}
for (const loc of LOCALES) if (!dict[loc]) dict[loc] = dict.en;

// Write every non-English locale as its own small JSON file, fetched at
// runtime only when a player actually needs that language.
const outDir = join(ROOT, 'public/i18n');
mkdirSync(outDir, { recursive: true });
for (const loc of LOCALES) {
  if (loc === 'en') continue;
  writeFileSync(join(outDir, `room.${loc}.json`), JSON.stringify(dict[loc]));
}

const boot = `
  <!-- i18n:room:start (generated by scripts/i18n-room-build.mjs — do not edit) -->
  <script>
  (function () {
    var LOCALES = ${JSON.stringify(LOCALES)};
    var DICT = { en: ${JSON.stringify(dict.en)} };
    var lang = 'en';
    try { lang = localStorage.getItem('hk_lang') || ''; } catch (e) {}
    if (LOCALES.indexOf(lang) === -1) {
      var nav = (navigator.language || 'en').toLowerCase();
      if (nav.indexOf('pt') === 0) lang = 'pt-br';
      else { var two = nav.slice(0, 2); lang = LOCALES.indexOf(two) !== -1 ? two : 'en'; }
    }
    var STR = DICT.en;
    window.__I18N__ = STR;
    window.t = function (key, params) {
      var s = (STR && STR[key] != null) ? STR[key] : (DICT.en[key] != null ? DICT.en[key] : key);
      if (params) for (var k in params) s = s.split('{' + k + '}').join(params[k]);
      return s;
    };
    try { document.documentElement.lang = lang; } catch (e) {}
    function fill() {
      document.querySelectorAll('[data-i18n]').forEach(function (el) {
        var v = window.t(el.getAttribute('data-i18n'));
        if (v != null) { el.textContent = v; if (el.hasAttribute('data-text')) el.setAttribute('data-text', v); }
      });
      document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
        var v = window.t(el.getAttribute('data-i18n-html')); if (v != null) el.innerHTML = v;
      });
      document.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
        var v = window.t(el.getAttribute('data-i18n-ph')); if (v != null) el.setAttribute('placeholder', v);
      });
    }
    if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', fill);
    else fill();
    // Non-English players: fetch just their locale instead of shipping all of
    // them inline, then re-fill once it lands.
    if (lang !== 'en') {
      fetch('/i18n/room.' + lang + '.json')
        .then(function (r) { return r.ok ? r.json() : null; })
        .then(function (data) {
          if (!data) return;
          DICT[lang] = data;
          STR = data;
          window.__I18N__ = STR;
          try { document.documentElement.lang = lang; } catch (e) {}
          fill();
        })
        .catch(function () { /* stay on English fallback */ });
    }
  })();
  </script>
  <!-- i18n:room:end -->
`;

let html = readFileSync(join(ROOT, 'public/game.html'), 'utf8');
html = html.replace(/\n?\s*<!-- i18n:room:start[\s\S]*?<!-- i18n:room:end -->\n?/g, '\n');
// Inject the bootstrap immediately before name.js so window.t exists for game.js.
html = html.replace('  <script src="name.js"></script>', `${boot}  <script src="name.js"></script>`);
writeFileSync(join(ROOT, 'public/game.html'), html);

const n = Object.keys(dict.en).length;
console.log(`room dict: en (${n} strings) embedded inline; ${LOCALES.length - 1} other locales written to public/i18n/*.json for on-demand fetch`);
